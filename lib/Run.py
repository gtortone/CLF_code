class RunBase:

    # laser trigger pulses generated by the FPGA (physical units, converted with the hw profile)
    PULSE_WIDTH_S = 100e-6      # width of both trigger outputs
    PULSE_ENERGY_S = 174e-6     # delay between the two triggers (laser $DPW 140 us -> 174 us, maximum)

    def __init__(self, dc : DeviceCollection, params):
        self.dc = dc
        self.params = params
        self.identity = str.lower(self.params['identity'])
        self.hw = get_profile(self.params)

        self.logger = logging.getLogger("run")
        self.logger.setLevel(logging.INFO)
        if not self.logger.handlers:
            formatter = logging.Formatter('%(asctime)s - %(classname)s::%(funcName)s - %(levelname)s - %(message)s')
            handler = TimedRotatingFileHandler('logs/run.log', when='midnight', 
                atTime=datetime.time(hour=18, minute=0))
            handler.setFormatter(formatter)
            self.logger.addHandler(handler)
        self.log = partial(self.logger.log, extra={'classname': self.__class__.__name__})

        # logs/shots.csv (one row per shot); run_id is set again by RunManager.submit
        # from the "start <TYPE> run" line, as the dashboard does
        self.shots_csv = ShotsCsv.shots_logger()
        self.run_type = self.__class__.__name__[3:].upper()        # RunFD -> FD, RunCalib -> CALIB
        self.run_id = f"{self.run_type}-{int(time.time())}"
        self.series = ""                                          # calibration: energy, pol0, ...

    @property
    def energy_ticks(self):
        return self.hw.ticks(self.PULSE_ENERGY_S)

    def trigger_delay(self, run):
        """pps_delay register for 'fd' or 'tank' runs, from parameters.yml."""
        return trigger_delay_ticks(self.params, run, self.energy_ticks)

    def configure_shots(self, pps_delay, period_s, nshots):
        """Write the FPGA shot sequence: delay from PPS (ticks), period (s), number of shots."""
        self.dc.fpga.write_register('pps_delay', pps_delay)
        self.dc.fpga.write_register('pulse_width', self.hw.ticks(self.PULSE_WIDTH_S))
        self.dc.fpga.write_register('pulse_energy', self.energy_ticks)
        self.dc.fpga.write_register('pulse_period', self.hw.period(period_s))
        self.dc.fpga.write_register('shots_num', nshots)

    def sync_time(self):
        """Check (and align if needed) the FPGA seconds counter used in the shot timestamps.
        On failure the run goes on: shots are triggered by the PPS, not by this counter."""
        levels = {'info': logging.INFO, 'warning': logging.WARNING, 'error': logging.ERROR}
        ok = TimeSync.ensure(self.dc.fpga, lambda lvl, msg: self.log(levels[lvl], msg, stacklevel=3))
        if not ok:
            self.log(logging.ERROR, "timestamps of this run will have wrong seconds")
        return ok

    SHOT_TIMEOUT_S = 2.5        # 1 Hz sequences: first shot within 1 s + pps delay, then 1 s apart

    def start_shots(self, *radiometers):
        """Start the FPGA shot sequence, dropping timestamp packets and radiometer
        readings left from before (one triggered reading per shot from here on)."""
        self.dc.data.flush()
        for name in radiometers:
            self.dc.get_radiometer(name).flush_buffers()
        self.dc.fpga.write_dio('laser_start', 1)

    def log_shot(self, i, radiometer, also=()):
        """Read radiometer power and FPGA timestamp of shot i (0-based) and log them (GPS time).

        The packet is matched by its shot number (i+1 in the sequence), not by arrival
        order: a missing shot gives zeros for that shot only.

        Radiometer readings are taken by time, not by count:
        - before the shot, whatever the radiometer already sent is dropped (logged): it
          belongs to an earlier shot (late reading, or the last shot of the previous run
          left in the port, which the flush at start did not always remove);
        - the FPGA packet is read next: it waits for the shot itself (the first one comes
          up to 1 s + trigger delay after laser_start);
        - then the reading of this shot, already there or within READ_TIMEOUT_S (< 1 s,
          before the next shot). No reading: NaN for this shot only.
        (The old order, radiometer first with a 0.8 s wait, lost a shot at the start
        and shifted every following power by one shot.)

        `also`: other radiometers read for the same shot (e.g. Rad1 next to Rad3 in the
        calibration run), all within the same READ_TIMEOUT_S; their values are appended
        to the line as ", power Rad1: <value>" (the main one stays in "shot: <value>")."""
        rad = self.dc.get_radiometer(radiometer)
        others = [self.dc.get_radiometer(name) for name in also]
        for r in [rad] + others:
            r.discard_pending()
        p = self.dc.data.read_shot(i + 1, self.SHOT_TIMEOUT_S)
        if others:
            power, *other_powers = read_powers([rad] + others)
        else:
            power, other_powers = rad.read_power(), []
        extra = "".join(f", power {name}: {value}" for name, value in zip(also, other_powers))
        if p is None:
            seconds, counter, pps, counter_cycles = 0, 0, 0, 0        # 0 = no packet for this shot
        else:
            # whole ns: the tick is 10 ns (hw v1) or 32.55 ns (hw v2), decimals add nothing
            seconds, counter, pps, counter_cycles = p.seconds, round(p.counter), round(p.pps_delta), p.shot
        gps_seconds = unix_to_gps(seconds) if seconds else 0
        self.log(logging.INFO, f'power {i} shot: {power}, gps_seconds: {gps_seconds}, counter: {counter}, '
                               f'pps distance: {pps}ns, counter cycle: {counter_cycles}{extra}', stacklevel=2)
        try:
            powers = dict(zip([radiometer, *also], [power, *other_powers]))
            self.shots_csv.info(ShotsCsv.row(self.run_id, self.run_type, self.series, i, gps_seconds,
                                             counter, pps, counter_cycles, powers))
        except Exception as e:          # the CSV is a copy for the analyses: never stop a run
            self.log(logging.ERROR, f"shots.csv not written: {e}")
        return power

    LASER_READY_TIMEOUT_S = 600     # TEC/diodes conditioning in STANDBY until fire authorization

    def wait_laser_ready(self):
        """Wait (wall clock) for the laser fire authorization, logging its temperatures."""
        start = time.monotonic()
        while not self.dc.laser.fire_auth():
            elapsed = time.monotonic() - start
            if elapsed >= self.LASER_READY_TIMEOUT_S:
                self.log(logging.ERROR, f"laser fire authorization timeout ({self.LASER_READY_TIMEOUT_S}s) - run interrupted", stacklevel=2)
                return False
            self.log(logging.INFO, self.dc.laser.temperature(), stacklevel=2)
            time.sleep(1)
        self.log(logging.INFO, f"laser fire authorization after {time.monotonic() - start:.0f}s", stacklevel=2)
        return True

    def close_cover_wait(self, timeout_s=120):
        """Wait for the RAMAN cover to close after its outlet was switched off. False on timeout."""
        self.log(logging.INFO, "wait for open limit switch release")
        if not self.wait_for(lambda: not self.dc.fpga.read_dio('cover_raman_open'),
                             timeout_s, "limit switch release"):
            return False
        self.log(logging.INFO, "done")

        self.log(logging.INFO, "wait cover closing")
        if not self.wait_for(lambda: self.dc.fpga.read_dio('cover_raman_open') != self.dc.fpga.read_dio('cover_raman_closed'),
                             timeout_s, "cover close"):
            return False
        self.log(logging.INFO, "done")
        return True

    def wait_for(self, condition, timeout_s, what):
        """Poll condition() once per second. True as soon as it holds, False (logged) after timeout_s."""
        for _ in range(timeout_s):
            if condition():
                return True
            time.sleep(1)
        if condition():
            return True
        self.log(logging.ERROR, f"{what} timeout ({timeout_s}s)", stacklevel=2)
        return False

    def safe_abort(self):
        """abort() (covers closed, laser standby, outlets and inverter off), never raising.

        Skipped when the inverter is off: the RPC is then unpowered and its (blocking by
        design) waits would never end, while everything is already without power."""
        try:
            if not self.dc.fpga.read_dio('inverter'):
                self.log(logging.INFO, "inverter off: nothing to shut down")
                return
            self.abort()
        except Exception as e:
            self.log(logging.ERROR, f"exception occurred during abort: {e}")

    def execute(self, do_prepare=True, do_finish=True):
        ret = None
        if do_prepare:
            try:
                ret = self.prepare()
            except Exception as e:
                self.log(logging.ERROR, f"exception occurred during prepare: {e}")
            if ret != 0:
                # a failed prepare can leave a cover open or the laser in fire mode:
                # always go to a safe state, also for runs that keep instruments on
                self.log(logging.ERROR, "prepare failed: shutting down")
                self.safe_abort()
                return
        if ret == 0:        # check if run preparation is completed
            try:
                self.run()
            except Exception as e:
                self.log(logging.ERROR, f"exception occurred during run: {e}: shutting down")
                self.safe_abort()
                return
        if do_finish:
            try:
                self.finish()
            except Exception as e:
                self.log(logging.ERROR, f"exception occurred during finish: {e}")


